/// Defines [`ModelId`] and its table from one list.
macro_rules! models {
    ($( $(#[$doc:meta])* $variant:ident = $id:literal, $provider:ident; )*) => {
        /// Model id: a closed table embedded in this version (normalised ids as the desktop
        /// pricing table writes them). Any other model is [`ModelId::Unknown`].
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
        #[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
        pub enum ModelId {
            $( $(#[$doc])* #[serde(rename = $id)] $variant, )*
            #[serde(rename = "unknown")]
            Unknown,
        }

        impl ModelId {
            /// Every known model with its id and provider (not [`ModelId::Unknown`]).
            pub const TABLE: &'static [(ModelId, &'static str, Provider)] = &[
                $( (ModelId::$variant, $id, Provider::$provider), )*
            ];
        }
    };
}

