/// Providers whose accounts can be shared in version 1.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "snake_case")]
pub enum Provider {
    Claude,
    Codex,
}

impl Provider {
    pub const ALL: [Provider; 2] = [Provider::Claude, Provider::Codex];

    /// Wire id (`claude`, `codex`).
    pub fn as_str(self) -> &'static str {
        match self {
            Provider::Claude => "claude",
            Provider::Codex => "codex",
        }
    }

    /// Exact wire id → provider. Anything else is not shareable.
    pub fn parse(id: &str) -> Option<Provider> {
        Provider::ALL.into_iter().find(|p| p.as_str() == id)
    }
}

/// Subscription plan. Each provider has its own subset (see [`PlanCode::allowed_for`]);
/// anything else is [`PlanCode::Unknown`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "snake_case")]
pub enum PlanCode {
    Free,
    Pro,
    Max,
    #[serde(rename = "max_5x")]
    Max5x,
    #[serde(rename = "max_20x")]
    Max20x,
    Team,
    Enterprise,
    Go,
    Plus,
    Business,
    Edu,
    Unknown,
}

impl PlanCode {
    pub const ALL: [PlanCode; 12] = [
        PlanCode::Free,
        PlanCode::Pro,
        PlanCode::Max,
        PlanCode::Max5x,
        PlanCode::Max20x,
        PlanCode::Team,
        PlanCode::Enterprise,
        PlanCode::Go,
        PlanCode::Plus,
        PlanCode::Business,
        PlanCode::Edu,
        PlanCode::Unknown,
    ];
    /// Claude plans.
    pub const CLAUDE: [PlanCode; 8] = [
        PlanCode::Free,
        PlanCode::Pro,
        PlanCode::Max,
        PlanCode::Max5x,
        PlanCode::Max20x,
        PlanCode::Team,
        PlanCode::Enterprise,
        PlanCode::Unknown,
    ];
    /// Codex (ChatGPT) plans.
    pub const CODEX: [PlanCode; 9] = [
        PlanCode::Free,
        PlanCode::Go,
        PlanCode::Plus,
        PlanCode::Pro,
        PlanCode::Team,
        PlanCode::Business,
        PlanCode::Enterprise,
        PlanCode::Edu,
        PlanCode::Unknown,
    ];

    /// Wire code (`max_20x`).
    pub fn as_str(self) -> &'static str {
        match self {
            PlanCode::Free => "free",
            PlanCode::Pro => "pro",
            PlanCode::Max => "max",
            PlanCode::Max5x => "max_5x",
            PlanCode::Max20x => "max_20x",
            PlanCode::Team => "team",
            PlanCode::Enterprise => "enterprise",
            PlanCode::Go => "go",
            PlanCode::Plus => "plus",
            PlanCode::Business => "business",
            PlanCode::Edu => "edu",
            PlanCode::Unknown => "unknown",
        }
    }

    /// The plans `provider` can report.
    pub fn allowed_for(self, provider: Provider) -> bool {
        match provider {
            Provider::Claude => PlanCode::CLAUDE.contains(&self),
            Provider::Codex => PlanCode::CODEX.contains(&self),
        }
    }

    /// Translate a plan label as a provider reports it (`"Max 20x"`, `"plus"`, `"Pro"`) into a
    /// code: trimmed, lower case, spaces and `-` as `_`, then matched EXACTLY against the
    /// provider's set. Anything else (including any free text) is [`PlanCode::Unknown`].
    pub fn parse(provider: Provider, label: &str) -> PlanCode {
        let code = label
            .trim()
            .to_ascii_lowercase()
            .split([' ', '-', '_'])
            .filter(|s| !s.is_empty())
            .collect::<Vec<_>>()
            .join("_");
        PlanCode::ALL
            .into_iter()
            .find(|p| p.as_str() == code && p.allowed_for(provider))
            .unwrap_or(PlanCode::Unknown)
    }
}

/// Quota window id. Each provider has its own subset (see [`WindowId::allowed_for`]); any
/// other window (custom endpoints, spend, extra usage …) is not sent.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "snake_case")]
pub enum WindowId {
    /// Claude 5-hour session.
    Session,
    /// Claude 7-day, all models.
    SevenDay,
    SevenDayOpus,
    SevenDaySonnet,
    WeeklyScoped,
    /// Codex primary window.
    Primary,
    /// Codex secondary window.
    Secondary,
}

impl WindowId {
    pub const ALL: [WindowId; 7] = [
        WindowId::Session,
        WindowId::SevenDay,
        WindowId::SevenDayOpus,
        WindowId::SevenDaySonnet,
        WindowId::WeeklyScoped,
        WindowId::Primary,
        WindowId::Secondary,
    ];

    /// Wire id (`seven_day`).
    pub fn as_str(self) -> &'static str {
        match self {
            WindowId::Session => "session",
            WindowId::SevenDay => "seven_day",
            WindowId::SevenDayOpus => "seven_day_opus",
            WindowId::SevenDaySonnet => "seven_day_sonnet",
            WindowId::WeeklyScoped => "weekly_scoped",
            WindowId::Primary => "primary",
            WindowId::Secondary => "secondary",
        }
    }

    /// The windows `provider` reports.
    pub fn allowed_for(self, provider: Provider) -> bool {
        match provider {
            Provider::Claude => matches!(
                self,
                WindowId::Session
                    | WindowId::SevenDay
                    | WindowId::SevenDayOpus
                    | WindowId::SevenDaySonnet
                    | WindowId::WeeklyScoped
            ),
            Provider::Codex => matches!(self, WindowId::Primary | WindowId::Secondary),
        }
    }

    /// Exact window id of `provider` → id. `None` = the window is not sent.
    pub fn parse(provider: Provider, id: &str) -> Option<WindowId> {
        WindowId::ALL
            .into_iter()
            .find(|w| w.as_str() == id && w.allowed_for(provider))
    }
}

