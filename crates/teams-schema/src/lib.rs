/// `quota.snapshot`: the COMPLETE quota state of one account. It replaces the previous one
/// (a window missing from it is removed); an empty `windows` is a tombstone (account removed
/// or excluded from sharing).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct QuotaSnapshot {
    /// 16 lowercase hex characters derived on the device; never an account name or e-mail.
    #[cfg_attr(feature = "schema", schemars(pattern(validate::ACCOUNT_REF_PATTERN)))]
    pub account_ref: String,
    pub provider: Provider,
    pub plan: PlanCode,
    /// Monotonic per account, persisted on the device.
    pub seq: u64,
    /// When the provider reading was taken (unix seconds).
    pub observed_at: i64,
    /// Empty = tombstone.
    #[cfg_attr(feature = "schema", schemars(length(max = 8)))]
    pub windows: Vec<QuotaWindow>,
}

/// One quota window of a [`QuotaSnapshot`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct QuotaWindow {
    pub id: WindowId,
    pub kind: WindowKind,
    /// Which ring the window drives on the device, when any.
    pub role: Option<WindowRole>,
    /// Percent used, 0–100. `None` = unknown.
    #[cfg_attr(feature = "schema", schemars(range(min = 0.0, max = 100.0)))]
    pub used_percent: Option<f64>,
    /// Reset time (unix seconds). `None` = unknown.
    pub resets_at: Option<i64>,
    /// Full window length in seconds. `None` = unknown.
    #[cfg_attr(feature = "schema", schemars(range(min = 1)))]
    pub window_seconds: Option<i64>,
}

/// `usage.hour`: the ABSOLUTE token totals of one natural key (device, account, provider,
/// model, UTC hour). Each change is a new revision (`rev + 1`, new event id); zero totals are a
/// tombstone.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct UsageHour {
    #[cfg_attr(feature = "schema", schemars(pattern(validate::ACCOUNT_REF_PATTERN)))]
    pub account_ref: String,
    pub provider: Provider,
    pub model: ModelId,
    /// Start of the UTC hour (unix seconds, multiple of 3600).
    pub hour_start: i64,
    /// Revision, monotonic per natural key, starting at 1.
    #[cfg_attr(feature = "schema", schemars(range(min = 1)))]
    pub rev: u64,
    pub tokens: Tokens,
}

/// Token counts of a [`UsageHour`]. `cache_write_1h` is a part of `cache_write`, not an
/// addition to it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Tokens {
    pub input: u64,
    pub output: u64,
    pub cache_read: u64,
    pub cache_write: u64,
    /// 1-hour cache writes, included in `cache_write`.
    #[serde(rename = "cacheWrite1h")]
    pub cache_write_1h: u64,
}

impl Tokens {
    /// All counts are zero (a tombstone revision).
    pub fn is_zero(&self) -> bool {
        *self == Tokens::default()
    }
}

/// `device.heartbeat`: liveness of the device's queue. Confirms no window value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Heartbeat {
    /// Events waiting on the device.
    pub queued: u32,
    /// Events the device dropped (queue full) since the previous heartbeat.
    pub dropped: u32,
}

