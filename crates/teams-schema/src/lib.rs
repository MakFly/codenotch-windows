impl ModelId {
    /// Wire id (`claude-opus-5-5`, `unknown`).
    pub fn as_str(self) -> &'static str {
        ModelId::TABLE
            .iter()
            .find(|(m, _, _)| *m == self)
            .map_or("unknown", |(_, id, _)| id)
    }

    /// Provider of a known model (`None` for [`ModelId::Unknown`]).
    pub fn provider(self) -> Option<Provider> {
        ModelId::TABLE
            .iter()
            .find(|(m, _, _)| *m == self)
            .map(|(_, _, p)| *p)
    }

    /// Whether this model can appear in a `usage.hour` of `provider` (`unknown` always can).
    pub fn allowed_for(self, provider: Provider) -> bool {
        self.provider().is_none_or(|p| p == provider)
    }

    /// An already-normalised model id (see the desktop pricing table), matched EXACTLY against
    /// the table of `provider`. Anything else is [`ModelId::Unknown`].
    pub fn parse(provider: Provider, normalised: &str) -> ModelId {
        ModelId::TABLE
            .iter()
            .find(|(_, id, p)| *id == normalised && *p == provider)
            .map_or(ModelId::Unknown, |(m, _, _)| *m)
    }
}
