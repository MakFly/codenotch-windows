//! # codenotch-teams-schema
//!
//! The closed event contract (version 1) a CodeNotch device sends to a CodeNotch Teams server.
//! Plain serde types, closed value sets and validation only: no I/O, no dependency on
//! `codenotch-core`, so both the desktop app and a server can share it.
//!
//! | item | what |
//! |---|---|
//! | [`Batch`] | envelope of one upload: device, versions, events |
//! | [`RawEvent`] | closed event envelope; `kind` is dispatched before the payload is parsed |
//! | [`QuotaSnapshot`], [`QuotaWindow`] | complete quota state of one account (`quota.snapshot`) |
//! | [`UsageHour`], [`Tokens`] | absolute token totals of one account, model and UTC hour (`usage.hour`) |
//! | [`Heartbeat`] | device liveness (`device.heartbeat`) |
//! | [`Provider`], [`PlanCode`], [`WindowId`], [`WindowKind`], [`WindowRole`], [`ModelId`] | closed value sets |
//! | [`validate`] | [`ValidationError`], [`FORBIDDEN_KEYS`], [`Batch::parse`] |
//! | `schema` (feature) | the JSON Schema committed as `schema/usage-events.v1.json` |
//!
//! Privacy boundary (binding):
//! * No free-form string from a provider, a transcript or the user ever leaves the device. Every
//!   field is a number, an identifier generated by CodeNotch (uuid, account reference) or a
//!   value of a closed set. A value that does not map to a closed set is not sent (windows) or
//!   becomes `unknown` (plans, models).
//! * Every object is closed (`deny_unknown_fields`, `additionalProperties: false`).
//! * Validation errors never carry the offending value, only a reason code and a field name.
//!
//! Versioning: version 1 is immutable once published. Any change (field, enum value, kind)
//! makes a version 2 with its own schema file; nothing is ever added to version 1.
//!
//! Conventions: times are unix **seconds** (`i64`), percentages are **0–100 used** (`f64`),
//! unknown values are `None` (never 0).

#[cfg(feature = "schema")]
pub mod schema;
pub mod validate;

use serde::{Deserialize, Serialize};
use serde_json::Value;

pub use validate::{ValidationError, FORBIDDEN_KEYS};

/// Version of this contract. Immutable once published.
pub const SCHEMA_VERSION: u32 = 1;

/// Most events in one [`Batch`].
pub const MAX_BATCH_EVENTS: usize = 100;
/// Largest serialised [`Batch`], in bytes.
pub const MAX_BATCH_BYTES: usize = 64 * 1024;

/// `kind` of a [`QuotaSnapshot`] event.
pub const KIND_QUOTA_SNAPSHOT: &str = "quota.snapshot";
/// `kind` of a [`UsageHour`] event.
pub const KIND_USAGE_HOUR: &str = "usage.hour";
/// `kind` of a [`Heartbeat`] event.
pub const KIND_DEVICE_HEARTBEAT: &str = "device.heartbeat";
/// Every event kind of version 1.
pub const KINDS: [&str; 3] = [KIND_QUOTA_SNAPSHOT, KIND_USAGE_HOUR, KIND_DEVICE_HEARTBEAT];

// ---------------------------------------------------------------------------------------------
// Envelope
// ---------------------------------------------------------------------------------------------

/// One upload. Contains events of a single schema version.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Batch {
    /// Always [`SCHEMA_VERSION`] for this crate.
    pub schema_version: u32,
    /// When the device sent the batch (unix seconds).
    pub sent_at: i64,
    /// Device id (uuid v4) generated at pairing; must match the device token.
    #[cfg_attr(feature = "schema", schemars(pattern(validate::UUID_V4_PATTERN)))]
    pub device_id: String,
    /// CodeNotch version that built the batch (`0.1.0`).
    #[cfg_attr(feature = "schema", schemars(pattern(validate::APP_VERSION_PATTERN)))]
    pub app_version: String,
    /// Consent version the member accepted at pairing.
    pub consent_version: u32,
    /// Data epoch of the member (bumped when the member's server data is erased).
    pub data_epoch: u32,
    #[cfg_attr(feature = "schema", schemars(length(min = 1, max = 100)))]
    pub events: Vec<RawEvent>,
}

/// Closed event envelope (no `flatten`): `kind` selects the payload type, which is parsed only
/// after dispatch (see [`RawEvent::payload`]).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct RawEvent {
    /// uuid v4, one per event or per revision.
    #[cfg_attr(feature = "schema", schemars(pattern(validate::UUID_V4_PATTERN)))]
    pub event_id: String,
    /// When the event was produced (unix seconds).
    pub occurred_at: i64,
    /// One of [`KINDS`].
    #[cfg_attr(feature = "schema", schemars(schema_with = "schema::kind_schema"))]
    pub kind: String,
    /// The payload of `kind`.
    #[cfg_attr(feature = "schema", schemars(schema_with = "schema::payload_schema"))]
    pub payload: Value,
}

/// A typed event payload.
#[derive(Debug, Clone, PartialEq)]
pub enum EventPayload {
    QuotaSnapshot(QuotaSnapshot),
    UsageHour(UsageHour),
    Heartbeat(Heartbeat),
}

impl EventPayload {
    /// The `kind` string of this payload.
    pub fn kind(&self) -> &'static str {
        match self {
            EventPayload::QuotaSnapshot(_) => KIND_QUOTA_SNAPSHOT,
            EventPayload::UsageHour(_) => KIND_USAGE_HOUR,
            EventPayload::Heartbeat(_) => KIND_DEVICE_HEARTBEAT,
        }
    }
}

impl RawEvent {
    /// Build an event from a typed payload. The payload is validated first, so an event built
    /// here always passes [`RawEvent::validate`] (given a valid uuid and time).
    pub fn new(
        event_id: impl Into<String>,
        occurred_at: i64,
        payload: &EventPayload,
    ) -> Result<RawEvent, ValidationError> {
        payload.validate()?;
        let value = match payload {
            EventPayload::QuotaSnapshot(p) => serde_json::to_value(p),
            EventPayload::UsageHour(p) => serde_json::to_value(p),
            EventPayload::Heartbeat(p) => serde_json::to_value(p),
        }
        .map_err(|_| ValidationError::Malformed)?;
        let event = RawEvent {
            event_id: event_id.into(),
            occurred_at,
            kind: payload.kind().to_string(),
            payload: value,
        };
        event.validate_envelope()?;
        Ok(event)
    }
}

