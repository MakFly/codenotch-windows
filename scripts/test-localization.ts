import { chromium, expect } from '@playwright/test';

const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1100, height: 850 } });
  const page = await context.newPage();
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:1437/?demo=1');
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await page.getByRole('button', { name: 'Expand notch', exact: true }).hover();
  await page.getByRole('button', { name: /Claude, / }).hover();
  const usage = page.getByRole('region', { name: 'Claude usage' });
  await expect(usage).toContainText('7 days');
  await expect(usage.getByRole('button')).toHaveCount(2); // Close and refresh only.
  await expect(usage.getByRole('button', { name: /pin|keep open|Garder ouvert|Détacher/i })).toHaveCount(0);
  await page.screenshot({ animations: 'disabled', path: 'test-results/usage-english-no-pin.png' });
  await page.mouse.move(50, 50);
  await expect(usage).toHaveCount(0);
  await page.locator('.preview-caption button').click();
  await page.getByRole('button', { name: 'Appearance and alerts', exact: true }).click();
  await expect(page.getByLabel('Interface language', { exact: true })).toHaveText('English');
  await page.getByLabel('Interface language', { exact: true }).click();
  await page.getByRole('option', { name: 'Français', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('lang', 'fr');
  await expect(page.getByRole('heading', { name: 'Apparence et alertes', exact: true })).toBeVisible();
  await expect(page.getByLabel('Langue de l’interface', { exact: true })).toHaveText('Français');
  await page.screenshot({ path: 'test-results/preferences-french.png' });
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'fr');
  await page.locator('.preview-caption button').click();
  await page.getByRole('button', { name: 'Apparence et alertes', exact: true }).click();
  await page.getByLabel('Langue de l’interface', { exact: true }).click();
  await page.getByRole('option', { name: 'English', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await expect(page.getByLabel('Interface language', { exact: true })).toHaveText('English');
  await page.screenshot({ path: 'test-results/preferences-english.png' });
  await page.getByRole('button', { name: 'Accounts 3', exact: true }).click();
  await page.locator('.config-account-main').first().click();
  await expect(page.getByRole('dialog', { name: 'Configure account', exact: true })).toBeVisible();
  await expect(page.getByLabel('Account name', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'About', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'About usage readings' })).toBeVisible();
  await expect(page.locator('.help-content')).not.toContainText('Connecte-toi');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  expect(errors).toEqual([]);
  console.log('PASS: English default, no pin, hover dismissal, EN/FR live switch and persistence, localized quota labels, account form and help.');
} finally { await browser.close(); }
