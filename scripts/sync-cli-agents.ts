// Rebuilds data/cli-agents.json from Orca's agent catalog (github.com/stablyai/orca) and
// CodeNotch's own additions in data/cli-agents.overrides.json.
//   bun run sync:agents
import { readFileSync, writeFileSync } from "node:fs";

const ORCA = "https://raw.githubusercontent.com/stablyai/orca/main";
const SOURCES = [
  "src/renderer/src/lib/agent-catalog-entries-primary.ts",
  "src/renderer/src/lib/agent-catalog-entries-secondary.ts",
];
const CONFIG = "src/shared/tui-agent-config.ts";

type Override = { quota?: string; logo?: string; name?: string; install?: string };
const overrides: { exclude: string[]; agents: Record<string, Override> } = JSON.parse(
  readFileSync("data/cli-agents.overrides.json", "utf8"),
);

async function fetchText(path: string): Promise<string> {
  const response = await fetch(`${ORCA}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.text();
}

/** Catalog entries: one object literal per agent, in Orca's display order. */
function catalog(source: string) {
  return source
    .split(/\n\s*\{\s*\n/)
    .slice(1)
    .map((block) => {
      const get = (re: RegExp) => block.match(re)?.[1] ?? null;
      return {
        id: get(/id:\s*'([^']+)'/),
        name: get(/label:\s*translate\([^,]+,\s*'([^']+)'\)/) ?? get(/label:\s*'([^']+)'/),
        homepage: get(/homepageUrl:\s*'([^']+)'/),
      };
    })
    .filter((entry): entry is { id: string; name: string; homepage: string | null } => !!entry.id && !!entry.name);
}

/** Executables Orca looks for, per agent: `detectCmd` and its aliases, and runtimes it skips. */
function detection(config: string) {
  const result = new Map<string, { commands: string[]; windows: boolean }>();
  for (const match of config.matchAll(/^\s{2}'?([\w-]+)'?:\s*\{([\s\S]*?)^\s{2}\}/gm)) {
    const [, id, body] = match;
    const command = body.match(/detectCmd:\s*'([^']+)'/)?.[1];
    if (!command) continue;
    const aliases = [...(body.match(/detectCmdAliases:\s*\[([^\]]*)\]/)?.[1] ?? "").matchAll(/'([^']+)'/g)].map((m) => m[1]);
    const unsupported = body.match(/detectUnsupportedRuntimes:\s*\[([^\]]*)\]/)?.[1] ?? "";
    result.set(id, { commands: [command, ...aliases], windows: !unsupported.includes("win32") });
  }
  // Single-line entries: `autohand: { detectCmd: 'autohand', ... },`
  for (const match of config.matchAll(/^\s{2}'?([\w-]+)'?:\s*\{\s*detectCmd:\s*'([^']+)'[^\n]*\},?$/gm)) {
    if (!result.has(match[1])) result.set(match[1], { commands: [match[2]], windows: true });
  }
  return result;
}

const entries = (await Promise.all(SOURCES.map(fetchText))).flatMap(catalog);
const detect = detection(await fetchText(CONFIG));

const agents = entries
  .filter((entry) => !overrides.exclude.includes(entry.id))
  .filter((entry) => detect.get(entry.id)?.windows !== false)
  .map((entry) => {
    const extra = overrides.agents[entry.id] ?? {};
    return {
      id: entry.id,
      name: extra.name ?? entry.name,
      commands: detect.get(entry.id)?.commands ?? [],
      homepage: entry.homepage,
      install: extra.install ?? null,
      quota: extra.quota ?? null,
      logo: extra.logo ?? null,
    };
  })
  .filter((agent) => agent.commands.length > 0);

const missing = Object.keys(overrides.agents).filter((id) => !agents.some((a) => a.id === id));
if (missing.length) throw new Error(`Overrides for agents Orca no longer lists: ${missing.join(", ")}`);

writeFileSync(
  "data/cli-agents.json",
  JSON.stringify(
    {
      $comment: "Generated by scripts/sync-cli-agents.ts from github.com/stablyai/orca and data/cli-agents.overrides.json. Do not edit by hand.",
      source: `${ORCA}/${SOURCES[0]}`,
      agents,
    },
    null,
    2,
  ) + "\n",
);
console.log(`${agents.length} agents written to data/cli-agents.json`);
